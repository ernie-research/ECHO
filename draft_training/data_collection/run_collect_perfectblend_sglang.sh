#!/usr/bin/env bash
set -euo pipefail

# the target PerfectBlend collection with one in-process SGLang engine per node (TP=8),
# replacing the HF collector's 8-workers-per-node layout.
#
# Launch one instance per node:
#   mpirun -n 6 --allow-run-as-root -npernode 1 \
#     bash ${WORKSPACE:?set WORKSPACE}/SpecForge/examples/run_collect_perfectblend_sglang.sh
#
# Defaults target echo_mtp2-7_sft/step_4800 (24 backbone layers +
# num_nextn_predict_layers=7). The 7 MTP layers are skipped on load -- the engine
# serves the plain target, greedy, no speculation. SHARDS_PER_RANK keeps the global
# part count at 96 with 12 nodes (or 48 with 6), so the H5 layout the trainer's
# dataloader sees stays comparable with perfectblend_step5000_h5.

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT_DIR=$(dirname "$SCRIPT_DIR")

VENV_PATH=${VENV_PATH:-${WORKSPACE:?set WORKSPACE}/.venvs/h800-existing-cu13}
export VIRTUAL_ENV="$VENV_PATH"
export PATH="$VENV_PATH/bin:$HOME/.local/bin:$HOME/.cargo/bin:$PATH"
export PYTHONPATH="${WORKSPACE:?set WORKSPACE}/SpecStack/third_party/sglang/python:$ROOT_DIR${PYTHONPATH:+:$PYTHONPATH}"
export PYTHONUNBUFFERED=${PYTHONUNBUFFERED:-1}
export PYTORCH_CUDA_ALLOC_CONF=${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}
export SGLANG_ENABLE_JIT_DEEPGEMM=${SGLANG_ENABLE_JIT_DEEPGEMM:-0}
export NCCL_DEBUG=${NCCL_DEBUG:-WARN}
export NCCL_SOCKET_IFNAME=${NCCL_SOCKET_IFNAME:-bond0}
export NCCL_IB_DISABLE=${NCCL_IB_DISABLE:-0}
export NCCL_IB_GID_INDEX=${NCCL_IB_GID_INDEX:-3}
export NCCL_NET_GDR_LEVEL=${NCCL_NET_GDR_LEVEL:-SYS}

NNODES=${NNODES:-6}
NODE_RANK=${NODE_RANK:-${OMPI_COMM_WORLD_RANK:-}}
: "${NODE_RANK:?NODE_RANK or OMPI_COMM_WORLD_RANK must be set on every node}"
export NNODES NODE_RANK

ACCEPT_ROOT=${WORKSPACE:?set WORKSPACE}/paddle_hf_alignment
MODEL_PATH=${MODEL_PATH:-$ACCEPT_ROOT/ckpts/echo_mtp2-7_sft/step_4800/extracted/hf_checkpoint-4800}
TOKENIZER_PATH=${TOKENIZER_PATH:-$ACCEPT_ROOT/tokenizer_hf}
# Prompt corpus: the DSV4-flash t0 regeneration of PerfectBlend, 1,420,572 rows.
# Only its user/system turns are read -- the assistant turns are discarded and
# regenerated by MODEL_PATH -- so the prompt set stays identical to the one the
# echo1.5_sft_step5000 collection used, which is what makes the two datasets
# comparable. Recovered from <JOB_ID>'s trainer-0 mount and copied here
# so the pipeline does not depend on another job's workspace surviving.
INPUT_FILE_PATH=${INPUT_FILE_PATH:-${WORKSPACE:?set WORKSPACE}/perfectblend_prompts/perfectblend_deepseek_v4_flash_chat_t0_8k.jsonl}
OUTPUT_DIR=${OUTPUT_DIR:-${WORKSPACE:?set WORKSPACE}/perfectblend_mtp2_7_step4800_raw}

MAX_NEW_TOKENS=${MAX_NEW_TOKENS:-4096}
MAX_INPUT_TOKENS=${MAX_INPUT_TOKENS:-3072}
TEMPERATURE=${TEMPERATURE:-0.0}
TOP_P=${TOP_P:-0.95}
TP_SIZE=${TP_SIZE:-8}
MEM_FRACTION=${MEM_FRACTION:-0.85}
ROWS_IN_FLIGHT=${ROWS_IN_FLIGHT:-256}
SHARDS_PER_RANK=${SHARDS_PER_RANK:-8}
LOG_INTERVAL=${LOG_INTERVAL:-50}

mkdir -p "$OUTPUT_DIR"
echo "[the target collect/sglang] node=$NODE_RANK/$NNODES tp=$TP_SIZE shards_per_rank=$SHARDS_PER_RANK total_shards=$((NNODES * SHARDS_PER_RANK)) model=$MODEL_PATH output=$OUTPUT_DIR"

EXTRA_ARGS=()
if [[ "${RESUME:-0}" == "1" ]]; then EXTRA_ARGS+=(--resume); fi
if [[ -n "${NUM_SAMPLES:-}" ]]; then EXTRA_ARGS+=(--num-samples "$NUM_SAMPLES"); fi
if [[ -n "${CONTEXT_LENGTH:-}" ]]; then EXTRA_ARGS+=(--context-length "$CONTEXT_LENGTH"); fi
if [[ -n "${MAX_RUNNING_REQUESTS:-}" ]]; then EXTRA_ARGS+=(--max-running-requests "$MAX_RUNNING_REQUESTS"); fi
if [[ -n "${SPEC_ALGO:-}" ]]; then
  EXTRA_ARGS+=(--speculative-algorithm "$SPEC_ALGO"
               --speculative-num-steps "${SPEC_NUM_STEPS:-1}"
               --speculative-eagle-topk "${SPEC_TOPK:-1}"
               --speculative-num-draft-tokens "${SPEC_NDT:-2}")
  if [[ -n "${SPEC_DRAFT_PATH:-}" ]]; then
    EXTRA_ARGS+=(--speculative-draft-model-path "$SPEC_DRAFT_PATH")
  fi
fi

"$VENV_PATH/bin/python" "$ROOT_DIR/scripts/collect_perfectblend_sglang.py" \
  --model-path "$MODEL_PATH" \
  --tokenizer-path "$TOKENIZER_PATH" \
  --input-file-path "$INPUT_FILE_PATH" \
  --output-dir "$OUTPUT_DIR" \
  --max-new-tokens "$MAX_NEW_TOKENS" \
  --max-input-tokens "$MAX_INPUT_TOKENS" \
  --temperature "$TEMPERATURE" \
  --top-p "$TOP_P" \
  --tp-size "$TP_SIZE" \
  --mem-fraction-static "$MEM_FRACTION" \
  --rows-in-flight "$ROWS_IN_FLIGHT" \
  --shards-per-rank "$SHARDS_PER_RANK" \
  --log-interval "$LOG_INTERVAL" \
  "${EXTRA_ARGS[@]}"
